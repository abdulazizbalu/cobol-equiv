"""Generate results/SUMMARY.md from the committed CSV files.

    python -m cobol_equiv.report [--results results]

Only numbers present in the CSV files are reported.
"""

from __future__ import annotations

import argparse
import csv
from collections import Counter, OrderedDict
from pathlib import Path


def _read(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with path.open(encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def _table(header: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def oracle_section(rows: list[dict]) -> list[str]:
    if not rows:
        return []
    by_rule: "OrderedDict[str, Counter]" = OrderedDict()
    for r in rows:
        by_rule.setdefault(r["rule"], Counter())[r["outcome"]] += 1
    table = []
    tot = Counter()
    for rule, c in by_rule.items():
        n = sum(c.values())
        tot.update(c)
        table.append([rule, n, c["agree"], c["disagree"], c["unsupported"]])
    table.append(["**total**", sum(tot.values()), tot["agree"], tot["disagree"], tot["unsupported"]])
    out = ["## Runtime vs GnuCOBOL (oracle)", "",
           "Source: `results/oracle_cases.csv`, produced by `python -m cobol_equiv.oracle.run`. "
           "`agree`: byte-identical output. `unsupported`: the runtime refused the case "
           "(raised `Unsupported`) because it is outside the documented subset; "
           "these are listed below and are not counted as agreement.", ""]
    out += _table(["rule", "cases", "agree", "disagree", "unsupported"], table)
    reasons = Counter()
    for r in rows:
        if r["outcome"] == "unsupported":
            msg = r["python"].split("UNSUPPORTED ", 1)[1]
            key = msg.split(":")[0] if msg.startswith("PICTURE") else msg.split(" into ")[0]
            reasons[(r["rule"], key)] += 1
    if reasons:
        out += ["", "Unsupported cases by reason:", ""]
        out += _table(["rule", "reason", "cases"], [[k[0], k[1], v] for k, v in sorted(reasons.items())])
    bad = [r for r in rows if r["outcome"] == "disagree"]
    if bad:
        out += ["", "Disagreements (first 20):", ""]
        out += _table(["rule", "case", "params"], [[r["rule"], r["case"], r["params"]] for r in bad[:20]])
    return out + [""]


def corpus_section(rows: list[dict]) -> list[str]:
    if not rows:
        return []
    out = ["## Corpus: reference translations vs GnuCOBOL", "",
           "Source: `results/corpus.csv`, produced by `python -m cobol_equiv.harness.corpus_run`.", ""]
    out += _table(["program", "semantic area", "regression vectors", "generated inputs", "result"],
                  [[r["program"], r["area"], r["vectors"], r["generated"], r["result"]] for r in rows])
    return out + [""]


def mutation_section(rows: list[dict]) -> list[str]:
    if not rows:
        return []
    by_cat: "OrderedDict[str, Counter]" = OrderedDict()
    for r in rows:
        by_cat.setdefault(r["category"], Counter())[r["status"]] += 1
    table = []
    tot = Counter()
    for cat, c in by_cat.items():
        tot.update(c)
        table.append([cat, sum(c.values()), c["killed"], c["survived"]])
    table.append(["**total**", sum(tot.values()), tot["killed"], tot["survived"]])
    out = ["## Mutation testing of the harness", "",
           "Source: `results/mutation.csv`, produced by `python -m cobol_equiv.harness.mutation_run`. "
           "A mutant is a deliberately wrong copy of a reference translation. "
           "`killed`: the harness reported a difference against GnuCOBOL. "
           "`survived`: no input found a difference.", ""]
    out += _table(["category", "mutants", "killed", "survived"], table)
    surv = [r for r in rows if r["status"] == "survived"]
    if surv:
        out += ["", "Surviving mutants and why:", ""]
        out += _table(["program", "mutant", "why it survived"],
                      [[r["program"], r["mutant"], r["note"] or "(not analysed)"] for r in surv])
    return out + [""]


def build(results: Path) -> str:
    env = _read(results / "environment.csv")
    lines = ["# Results summary", "",
             "Generated by `python -m cobol_equiv.report` from the CSV files in this directory. "
             "Do not edit by hand.", ""]
    if env:
        lines += _table(["key", "value"], [[r["key"], r["value"]] for r in env]) + [""]
    lines += oracle_section(_read(results / "oracle_cases.csv"))
    lines += corpus_section(_read(results / "corpus.csv"))
    lines += mutation_section(_read(results / "mutation.csv"))
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    a = ap.parse_args(argv)
    res = Path(a.results)
    (res / "SUMMARY.md").write_text(build(res), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
