"""Reference translation of benchmark/corpus-e/omp-srchbin/program.cob."""

from cobol_equiv.runtime import COMP3, Alnum, Group, Num, Storage

ENTRY = [
    Alnum("ACCT-NO", "X(8)"),
    Num("ACCT-LIMIT", "S9(7)V99", usage=COMP3),
    Num("ACCT-BALANCE", "S9(7)V99", usage=COMP3),
    Alnum("LAST-NAME", "X(20)"),
    Alnum("FIRST-NAME", "X(15)"),
    Group("CLIENT-ADDR", [Alnum("STREET-ADDR", "X(25)"), Alnum("CITY-COUNTY", "X(20)"),
                          Alnum("USA-STATE", "X(15)")]),
    Alnum("RESERVED", "X(7)"),
    Alnum("COMMENTS", "X(50)"),
]
KEY = b"18011809"


def main(stdin: bytes, input_files: dict) -> tuple:
    data = input_files["ACCTREC"]
    size = 170
    recs = [data[i:i + size] for i in range(0, len(data) - len(data) % size, size)]
    table = Storage("ACCT-TABLE", [Group("ACCT-TABLE-ITEM", ENTRY, occurs=45)])
    for i, rec in enumerate(recs[:44], 1):  # loads at most 44 entries
        table.f("ACCT-TABLE-ITEM", i).set_raw(rec)
    # SEARCH ALL as generated by cobc: head = 0, tail = 46, idx = (head + tail) // 2
    head, tail = 0, 45 + 1
    while True:
        if head >= tail - 1:
            return b"Not Found\n", {}
        idx = (head + tail) // 2
        key = bytes(table.f("ACCT-NO", idx).raw)
        if key == KEY:
            return b"User with Acct No 18011809 is found!\n", {}
        if key < KEY:
            head = idx
        else:
            tail = idx
